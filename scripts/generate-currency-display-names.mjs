/**
 * Run in Node only (not Hermes). Uses @formatjs/intl-displaynames + CLDR locale data
 * to emit static maps for app-supported languages — avoids runtime polyfill crashes on RN.
 *
 * Usage: node scripts/generate-currency-display-names.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

import "@formatjs/intl-displaynames/polyfill-force.js";
import "@formatjs/intl-displaynames/locale-data/en.js";
import "@formatjs/intl-displaynames/locale-data/tr.js";
import "@formatjs/intl-displaynames/locale-data/de.js";
import "@formatjs/intl-displaynames/locale-data/fr.js";
import "@formatjs/intl-displaynames/locale-data/es.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

function parseIsoCodes(ts) {
  const codes = new Set();
  for (const m of ts.matchAll(/"([A-Z]{3})"/g)) codes.add(m[1]);
  return [...codes].sort();
}

function parseEnFallback(ts) {
  const map = {};
  for (const m of ts.matchAll(/"([A-Z]{3})"\s*:\s*"([^"]*)"/g)) {
    map[m[1]] = m[2];
  }
  return map;
}

const isoPath = path.join(root, "constants/iso4217ActiveCodes.ts");
const enPath = path.join(root, "constants/currencyNamesEn.ts");
const codes = parseIsoCodes(fs.readFileSync(isoPath, "utf8"));
const enFallback = parseEnFallback(fs.readFileSync(enPath, "utf8"));

const LOCALES = ["en", "tr", "de", "fr", "es"];
const display = {};

for (const loc of LOCALES) {
  display[loc] = {};
  const dn = new Intl.DisplayNames([loc], { type: "currency" });
  for (const code of codes) {
    let name = dn.of(code);
    if (!name || name === code) name = enFallback[code] ?? code;
    display[loc][code] = name;
  }
}

const outPath = path.join(root, "constants/currencyDisplayNames.generated.ts");
const pretty = JSON.stringify(display, null, 2);
const file = `/** Auto-generated by scripts/generate-currency-display-names.mjs — do not edit. */
export type AppLocale = "en" | "tr" | "de" | "fr" | "es";

export const CURRENCY_DISPLAY_NAMES: Record<AppLocale, Record<string, string>> = ${pretty};
`;

fs.writeFileSync(outPath, file);
console.log("Wrote", outPath, "locales:", LOCALES.join(", "), "codes:", codes.length);
